import { readFile, writeFile, access } from 'node:fs/promises';
import { items, skillGroups } from '../dist/data.js';
import { renderPortfolio, icon } from '../dist/render.js';
const root=new URL('../',import.meta.url);
const htmlPath=new URL('dist/index.html',root);
let html=await readFile(htmlPath,'utf8');
const marker=/<!-- PORTFOLIO_START -->[\s\S]*?<!-- PORTFOLIO_END -->/;
if(!marker.test(html))throw new Error('Missing portfolio rendering markers');
html=html.replace(marker,`<!-- PORTFOLIO_START -->\n${renderPortfolio()}\n<!-- PORTFOLIO_END -->`);
html=html.replace(/(<(?:a|span|button)\b[^>]*\bdata-icon="([^"]+)"[^>]*>)[\s\S]*?(<\/(?:a|span|button)>)/g,(_,start,name,end)=>start+icon(name)+end);
await writeFile(htmlPath,html);
const js=await readFile(new URL('dist/app.js',root),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
if(new Set(ids).size!==ids.length)throw new Error('Duplicate HTML IDs');
for(const m of js.matchAll(/getElementById\('([^']+)'\)/g))if(!ids.includes(m[1]))throw new Error(`Missing HTML element: ${m[1]}`);
const assets=new Set([...html.matchAll(/(?:href|src)="\/(assets\/[^"#?]+|Thuy-Le-Resume\.pdf)"/g)].map(m=>m[1]));
for(const name of assets)await access(new URL(`dist/${name}`,root));
if([...html.matchAll(/<img\b/g)].length!==1)throw new Error('Expected only the headshot image');
if(new Set(items.map(i=>i.id)).size!==items.length)throw new Error('Duplicate content IDs');
for(const item of items)if(item.url&&new URL(item.url).protocol!=='https:')throw new Error('Unsafe project URL');
console.log(`Rendered and verified ${items.length} chapters, ${skillGroups.flatMap(g=>g.skills).length} skills, ${ids.length} unique elements, and one headshot.`);
